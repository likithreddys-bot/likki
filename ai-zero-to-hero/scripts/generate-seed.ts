/**
 * Generates supabase/seed.sql from src/content (the single source of truth).
 * Usage: npm run seed:generate
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { shuffledCurriculum } from '../src/content/curriculum';

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;

const topics = shuffledCurriculum();
const out: string[] = [];
const p = (s = '') => out.push(s);

p('-- AI Zero to Hero — curriculum seed');
p('-- GENERATED by `npm run seed:generate` from src/content — edit the content files, not this file.');
p('-- Safe to re-run: topics/sessions/final quizzes are upserted; inline quizzes are replaced.');
p();
p('begin;');
p();
p('delete from public.inline_quizzes;');
p();

topics.forEach((t, ti) => {
  p(`-- ───────── Topic ${ti + 1}: ${t.title} ─────────`);
  p(
    `insert into public.topics (slug, title, description, order_index, cover_image_url, is_published)\n` +
      `values (${lit(t.slug)}, ${lit(t.title)}, ${lit(t.description)}, ${ti + 1}, ${lit(`/covers/${t.slug}.svg`)}, true)\n` +
      `on conflict (slug) do update set title = excluded.title, description = excluded.description,\n` +
      `  order_index = excluded.order_index, cover_image_url = excluded.cover_image_url, is_published = excluded.is_published;`,
  );
  p();

  t.sessions.forEach((s, si) => {
    const videos = s.videos.map((v) => ({ title: v.title, url: v.url, thumbnail: v.thumbnail }));
    p(
      `insert into public.sessions (topic_id, title, content_markdown, order_index, youtube_urls)\n` +
        `values ((select id from public.topics where slug = ${lit(t.slug)}), ${lit(s.title)}, ${lit(s.markdown)}, ${si + 1}, ${json(videos)})\n` +
        `on conflict (topic_id, order_index) do update set title = excluded.title,\n` +
        `  content_markdown = excluded.content_markdown, youtube_urls = excluded.youtube_urls;`,
    );
    s.quizzes.forEach((q, qi) => {
      p(
        `insert into public.inline_quizzes (session_id, question, options, correct_index, explanation, order_index)\n` +
          `values ((select s.id from public.sessions s join public.topics t on t.id = s.topic_id where t.slug = ${lit(t.slug)} and s.order_index = ${si + 1}),\n` +
          `  ${lit(q.question)}, ${json(q.options)}, ${q.correct}, ${lit(q.explanation)}, ${qi + 1});`,
      );
    });
    p();
  });

  const questions = t.finalQuiz.map((q) => ({
    question: q.question,
    options: q.options,
    correct_index: q.correct,
    explanation: q.explanation,
  }));
  p(
    `insert into public.final_quizzes (topic_id, questions)\n` +
      `values ((select id from public.topics where slug = ${lit(t.slug)}), ${json(questions)})\n` +
      `on conflict (topic_id) do update set questions = excluded.questions;`,
  );
  p();
});

p('commit;');

const file = resolve(__dirname, '../supabase/seed.sql');
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, out.join('\n') + '\n');

const counts = topics.map((t) => ({
  topic: t.title,
  sessions: t.sessions.length,
  inline: t.sessions.reduce((n, s) => n + s.quizzes.length, 0),
  final: t.finalQuiz.length,
}));
console.table(counts);
console.log(`wrote ${file} (${(out.join('\n').length / 1024).toFixed(1)} KB)`);
